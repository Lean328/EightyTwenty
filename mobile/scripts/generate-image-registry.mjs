#!/usr/bin/env node
/**
 * Generates src/assets/imageRegistry.ts from the files in assets/images.
 *
 * React Native can only bundle images through static `require()` calls, so every
 * bundled photo needs a literal entry. Mock data refers to photos by key
 * (e.g. 'menu/food/mighty-breakfast'); the registry resolves keys to bundled sources.
 *
 * Run after adding/removing images:  npm run images:registry
 */
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(import.meta.url), '..', '..');
const imagesDir = join(root, 'assets', 'images');
const out = join(root, 'src', 'assets', 'imageRegistry.ts');
const SKIP = new Set(['textures']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return SKIP.has(name) ? [] : walk(full);
    return ['.webp', '.png', '.jpg'].includes(extname(name)) ? [full] : [];
  });
}

const files = walk(imagesDir).sort();
mkdirSync(join(root, 'src', 'assets'), { recursive: true });
const lines = files.map((file) => {
  const rel = relative(imagesDir, file).split(sep).join('/');
  const key = rel.replace(/\.[^.]+$/, '');
  return `  '${key}': require('../../assets/images/${rel}'),`;
});

writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/generate-image-registry.mjs — do not edit by hand.
// Run \`npm run images:registry\` after adding or removing files in assets/images.

export const imageRegistry = {
${lines.join('\n')}
} as const;

export type ImageKey = keyof typeof imageRegistry;
`,
);
console.log(`Wrote ${files.length} entries to ${relative(root, out)}`);
